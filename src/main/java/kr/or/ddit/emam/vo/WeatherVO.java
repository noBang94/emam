package kr.or.ddit.emam.vo;

public class WeatherVO {
    private String local_name;
    private String local_nx;
    private String local_ny;

    public String getLocal_name() { return local_name; }

    public void setLocal_name(String local_name) { this.local_name = local_name; }

    public String getLocal_nx() { return local_nx; }

    public void setLocal_nx(String local_nx) { this.local_nx = local_nx; }

    public String getLocal_ny() { return local_ny; }

    public void setLocal_ny(String local_ny) { this.local_ny = local_ny; }
}
